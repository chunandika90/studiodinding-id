-- Studio Dinding CMS schema + seed data
-- Import this once via phpMyAdmin (or `mysql -u USER -p DBNAME < schema.sql`) into the database
-- you created for this site. Seed values are copied 1:1 from the current hardcoded site content,
-- so importing this does not change anything visitors see on go-live.

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- ---------------------------------------------------------------------------
-- admin_users
-- ---------------------------------------------------------------------------
DROP TABLE IF EXISTS admin_users;
CREATE TABLE admin_users (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  username VARCHAR(64) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uniq_username (username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- No row is seeded here on purpose: a correct bcrypt hash has to be generated by PHP
-- itself (password_hash()), not hand-written into a SQL file. After importing this
-- schema and filling in shared/config.local.php, open
-- https://cms.studiodinding.id/api/setup.php once in the browser — it creates the
-- admin login (admin / studiodinding123) using a real hash, then delete
-- cms/api/setup.php from the server (it refuses to run again once a user exists,
-- but deleting it afterward is the safer habit).

