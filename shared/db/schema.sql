-- ---------------------------------------------------------------------------
-- projects (Portfolio) + project_gallery
-- ---------------------------------------------------------------------------
DROP TABLE IF EXISTS project_gallery;
DROP TABLE IF EXISTS projects;

CREATE TABLE projects (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  slug VARCHAR(64) NOT NULL,
  name VARCHAR(255) NOT NULL,
  type ENUM('residential','commercial') NOT NULL DEFAULT 'residential',
  category_id INT UNSIGNED NULL,
  location VARCHAR(255) NOT NULL DEFAULT 'Indonesia',
  services VARCHAR(255) NOT NULL DEFAULT 'Architecture & Interior Design',
  status VARCHAR(64) NOT NULL DEFAULT 'Completed',
  project_type_label VARCHAR(64) NOT NULL DEFAULT 'Private Residence',
  quote TEXT NOT NULL,
  seo_title VARCHAR(255) NULL,
  seo_description VARCHAR(300) NULL,
  cover_img VARCHAR(255) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  published TINYINT(1) NOT NULL DEFAULT 1,
  created_by INT UNSIGNED NULL,
  updated_by INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uniq_slug (slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE project_gallery (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  project_id INT UNSIGNED NOT NULL,
  img VARCHAR(255) NOT NULL,
  span VARCHAR(16) NOT NULL DEFAULT 'span 1',
  ratio VARCHAR(16) NOT NULL DEFAULT '4/5',
  sort_order INT NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  KEY idx_project (project_id),
  CONSTRAINT fk_gallery_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

